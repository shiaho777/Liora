export const i18n = $state({
  locale: (typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('zh')
    ? 'zh'
    : 'en') as Locale,
});

export function setLocale(locale: string): void {
  if (locale === 'zh' || locale === 'en') {
    i18n.locale = locale;
    return;
  }
  i18n.locale = typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('zh')
    ? 'zh'
    : 'en';
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const table = dictionaries[i18n.locale] ?? dictionaries.en;
  let text = table[key] ?? dictionaries.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function localized(value: unknown): string {
  if (typeof value === 'string') return value;
  if (value && typeof value === 'object') {
    const record = value as Record<string, string>;
    return record[i18n.locale] ?? record.en ?? Object.values(record)[0] ?? '';
  }
  return '';
}
